
M = int(input("Введите возраст деда (M): "))
N = int(input("Введите возраст внука (N): "))
years = 0
while M != 2 * N:
    M += 1  # Дед становится старше на 1 год
    N += 1  # Внук становится старше на 1 год
    years += 1  # Увеличиваем количество лет
print(f"Через {years} лет дед станет вдвое старше внука.")
print(f"Возраст деда будет: {M} лет.")
print(f"Возраст внука будет: {N} лет.")


